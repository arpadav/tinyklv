//! Code generation for the `DecodePartial`, `ResumePartial` and one-shot `DecodeValue` impls
//!
//! Provides three entry points consumed by [`super::gen_decode_impl`], all methods of
//! [`DecodeCtx`]:
//!
//! * [`DecodeCtx::decode_partial_impl`] - emits the `DecodePartial` impl, which
//!   allocates a default partial struct and delegates to `ResumePartial`
//! * [`DecodeCtx::resume_partial_impl`] - emits the `ResumePartial` impl, the streaming
//!   decode loop (resumable across `feed` chunks via `Packet::NeedMore`)
//! * [`DecodeCtx::decode_value_impl`] - emits the one-shot `DecodeValue` impl: the same loop
//!   and `finalize`, in a single linear pass with no resume/`Packet` machinery (used by
//!   `decode_value`/`decode_frame`)
//!
//! The last two differ only in their impl header and prologue. Both get the loop itself from
//! [`DecodeCtx::frame_loop`], whose frame header and body come from
//! [`DecodeFraming`](super::framing::DecodeFraming) and whose exits come from [`LoopDriver`],
//! followed, when it can `break` ([`DecodeCtx::breaks`]), by the [`LoopCtx::finish`] tail, which
//! finalizes the accumulator once the loop `break`s
//!
//! Author: aav
// --------------------------------------------------
// local
// --------------------------------------------------
use super::{
    DecodeCtx, LoopCtx,
    loop_driver::{CursorSite, LoopDriver},
};

// --------------------------------------------------
// external
// --------------------------------------------------
use proc_macro2::TokenStream;
use quote::quote;

/// [`DecodeCtx`] implementation of the decode loop and the impls built around it
impl DecodeCtx<'_> {
    /// Emits the `logger!` call after the frame header, when the container set `debug`
    ///
    /// # Returns
    ///
    /// The log statement, or `None` without `debug`
    fn debug_key_val(&self) -> Option<TokenStream> {
        self.input
            .attrs
            .debug
            .is_some()
            .then(|| self.framing.debug_line())
    }

    /// Emits `#[allow(clippy::manual_range_patterns)]` for the decode fn, when the container set
    /// `deny_unknown_keys`
    ///
    /// The allowance covers the generated key alternation, so it is emitted only when a gate
    /// exists
    ///
    /// # Returns
    ///
    /// The attribute, or `None` without `deny_unknown_keys`
    fn pre_check_clippy_allow(&self) -> Option<TokenStream> {
        self.input.attrs.deny_unknown_keys.is_some().then(|| {
            let key = self.framing.key();
            let reason = format!(
                "the matches!({key}, K1 | K2 | ...) pattern is generated by the macro and cannot be avoided. this lint appears when keys are consecutive"
            );
            quote! {
                #[allow(
                    clippy::manual_range_patterns,
                    reason = #reason,
                )]
            }
        })
    }

    /// Emits the per-frame decode `loop { .. }` for `driver`
    ///
    /// Each iteration:
    ///
    /// 1. Leaves the loop through [`LoopDriver::clean_eof`] when the input is empty
    /// 2. Checkpoints the frame start as `checkpoint_inner`
    /// 3. Reads the frame header ([`LoopCtx::header`])
    /// 4. Evaluates `break_on`, when set ([`LoopCtx::break_on`]); then a separate frame of a
    ///    `size(implicit)` field's key decodes its value and skips the steps below
    ///    ([`LoopCtx::after_key`])
    /// 5. Logs the header, when `debug` is set
    /// 6. Rejects a key outside the known set ([`LoopDriver::reject`]), when `deny_unknown_keys`
    ///    is set; this runs before any value byte is consumed, in both framing modes
    /// 7. Decodes the value into its field ([`LoopCtx::body`]), then rejects a fused frame that
    ///    consumed no input
    ///
    /// A `break` leaves the loop for the [`LoopCtx::finish`] tail, which follows the loop only
    /// when it can `break` ([`Self::breaks`]); a loop that cannot diverges, and a tail after it
    /// would be unreachable code
    ///
    /// # Arguments
    ///
    /// * `driver` - The loop exit policy
    ///
    /// # Returns
    ///
    /// The `loop { .. }` statement, then the tail expression when the loop can `break`
    fn frame_loop(&self, driver: LoopDriver) -> TokenStream {
        let input = self.input;
        // --------------------------------------------------
        // the loop context, and the exit taken on a clean end of input
        // --------------------------------------------------
        let lp = self.loop_ctx(driver);
        let clean_eof = driver.clean_eof();
        // --------------------------------------------------
        // the stages of one frame, in the order the loop runs them
        // --------------------------------------------------
        let header = lp.header();
        let break_on = lp.break_on();
        let debug_key_val = self.debug_key_val();
        let gate = input
            .attrs
            .deny_unknown_keys
            .is_some()
            .then(|| self.unknown_key_gate(driver));
        let body = lp.body();
        // --------------------------------------------------
        // the tail follows the loop only when the loop can `break`
        // --------------------------------------------------
        let finish = self.breaks(driver, break_on.as_ref()).then(|| lp.finish());
        // --------------------------------------------------
        // the stages after `break_on`, once the frame's length is read
        // --------------------------------------------------
        let frame = lp.after_key(quote! {
            #debug_key_val
            #gate
            #body
        });
        // --------------------------------------------------
        // emit the loop: the clean end of input, a checkpoint, then each stage
        // --------------------------------------------------
        quote! {
            loop {
                if input.eof_offset() == 0 {
                    #clean_eof
                }
                let checkpoint_inner = input.checkpoint();
                #header
                #break_on
                #frame
            }
            #finish
        }
    }

    /// Whether the loop emitted for `driver` contains a `break`
    ///
    /// ORs the report of each emitter that can put a `break` into the loop:
    /// [`LoopDriver::clean_eof_breaks`], a `Some` from [`LoopCtx::break_on`],
    /// [`DecodeFraming::unknown_key_breaks`](super::framing::DecodeFraming::unknown_key_breaks),
    /// and a field's `break_on`, whose `Done` breaks
    ///
    /// # Arguments
    ///
    /// * `driver` - The loop exit policy
    /// * `break_on` - What [`LoopCtx::break_on`] emitted into the loop
    ///
    /// # Returns
    ///
    /// `true` when the loop can `break` to the [`LoopCtx::finish`] tail
    fn breaks(&self, driver: LoopDriver, break_on: Option<&TokenStream>) -> bool {
        driver.clean_eof_breaks()
            || break_on.is_some()
            || self.framing.unknown_key_breaks()
            || self
                .input
                .klv_fields()
                .any(|(_, attrs)| attrs.break_on.is_some())
    }

    /// Emits the `deny_unknown_keys` gate, `if !matches!(#key, #pattern) { #reject }`, where
    /// `#key` is [`DecodeFraming::key`](super::framing::DecodeFraming::key)
    ///
    /// The gate runs after the frame header and before any value byte is consumed, so an unknown
    /// key is rejected with the `invalid key (expected one of the keys defined on ..)` message,
    /// never the truncation a declared length overrunning the input would otherwise produce. The
    /// pattern is the `|`-joined alternation of every field's `#[klv(key = ..)]` literal, never
    /// empty: a decode impl is generated only for a struct with at least one KLV field
    ///
    /// # Arguments
    ///
    /// * `driver` - The loop exit policy the rejection returns through ([`LoopDriver::reject`])
    ///
    /// # Returns
    ///
    /// The gate statement
    fn unknown_key_gate(&self, driver: LoopDriver) -> TokenStream {
        let name = &self.input.ident;
        let key = self.framing.key();
        // --------------------------------------------------
        // each klv field's declared key expression, spliced with `|` separators
        // --------------------------------------------------
        let keys = self.input.klv_fields().map(|(_, attrs)| &attrs.key);
        let pattern = quote! { #(#keys)|* };
        let reject = driver.reject(&quote! {
            concat!(
                "invalid key (expected one of the keys defined on `",
                stringify!(#name),
                "`; to turn this off, remove `deny_unknown_keys`)",
            )
        });
        quote! {
            if !matches!(#key, #pattern) {
                #reject
            }
        }
    }

    /// Pairs `driver` with this container, its framing, stream and accumulator types
    ///
    /// # Arguments
    ///
    /// * `driver` - The loop exit policy
    ///
    /// # Returns
    ///
    /// The [`LoopCtx`] the loop's header, body and exits are emitted against
    fn loop_ctx(&self, driver: LoopDriver) -> LoopCtx<'_> {
        LoopCtx {
            input: self.input,
            driver,
            framing: self.framing,
            stream: &self.stream,
            partial_ty: &self.partial_ty,
        }
    }

    /// Generates the `ResumePartial` trait implementation containing the streaming decode loop
    ///
    /// Each call resumes decoding into the caller's `__acc` and returns `Packet::NeedMore(__acc)`
    /// when the input runs out mid-frame or between frames, `Packet::Ready` once the loop ends and
    /// `finalize` succeeds, or `Err` with a `&'static str` label; a fused container's exits follow
    /// the rules stated on `tinyklv::Framing`. The loop is [`Self::frame_loop`] with
    /// [`LoopDriver::Streaming`]
    ///
    /// # Returns
    ///
    /// A [`proc_macro2::TokenStream`] containing the complete `ResumePartial` impl block
    pub(super) fn resume_partial_impl(&self) -> TokenStream {
        let Self {
            input,
            ref stream,
            ref partial_ty,
            ..
        } = *self;
        let name = &input.ident;
        // --------------------------------------------------
        // the lint allowance for the key gate, and the streaming exit policy
        // --------------------------------------------------
        let pre_check_clippy_allow = self.pre_check_clippy_allow();
        let driver = LoopDriver::Streaming;
        // --------------------------------------------------
        // split generics
        // --------------------------------------------------
        let (impl_generics, ty_generics, where_clause) = input.generics.split_for_impl();
        // --------------------------------------------------
        // the frame loop, resuming into the caller's `__acc`
        // --------------------------------------------------
        let frame_loop = self.frame_loop(driver);
        // --------------------------------------------------
        // emit the `ResumePartial` impl around the loop
        // --------------------------------------------------
        quote! {
            #[doc(hidden)]
            #[automatically_derived]
            #[doc = concat!(" [`", stringify!(#name), "`] implementation of [`tinyklv::traits::ResumePartial`] for [`", stringify!(#stream), "`].")]
            impl #impl_generics ::tinyklv::traits::ResumePartial<#stream> for #name #ty_generics #where_clause {

                #pre_check_clippy_allow

                fn resume_partial(
                    input: &mut #stream,
                    mut __acc: #partial_ty,
                ) -> ::core::result::Result<
                    ::tinyklv::decoder::Packet<Self, #partial_ty>,
                    &'static str,
                > {
                    let checkpoint = input.checkpoint();
                    let _ = checkpoint;
                    #frame_loop
                }
            }
        }
    }

    /// Generates the one-shot direct `DecodeValue` implementation for a container
    ///
    /// `decode_value`/`decode_frame` are one-shot entry points: the caller already holds the
    /// complete value body, so they do NOT need the streaming `resume_partial` machinery
    /// (`Packet::NeedMore`, resumable accumulator). This emits a single linear pass over the input
    /// into a stack-local partial accumulator, then `Partial::finalize` - the same loop the
    /// streaming path uses, with [`LoopDriver::OneShot`] exits
    ///
    /// The loop ends, and the accumulated fields are finalized, where streaming would return
    /// `NeedMore` or `Ready` (see [`LoopDriver`]); a fused container's exits follow the rules
    /// stated on `tinyklv::Framing`
    ///
    /// The loop advances the cursor the container's [`CursorSite`] names: the caller's, or a
    /// local copy inside the block labelled `'__tinyklv_decode`, which every exit leaves and after
    /// which the copy is written back to the caller's
    ///
    /// # Returns
    ///
    /// A [`proc_macro2::TokenStream`] containing the complete one-shot `DecodeValue` impl block
    pub(super) fn decode_value_impl(&self) -> TokenStream {
        let Self {
            input,
            ref stream,
            ref partial_ty,
            ..
        } = *self;
        let name = &input.ident;
        // --------------------------------------------------
        // the lint allowance for the key gate, and the one-shot exit policy
        // --------------------------------------------------
        let pre_check_clippy_allow = self.pre_check_clippy_allow();
        let driver = LoopDriver::OneShot(self.cursor);
        // --------------------------------------------------
        // split generics
        // --------------------------------------------------
        let (impl_generics, ty_generics, where_clause) = input.generics.split_for_impl();
        // --------------------------------------------------
        // the frame loop, accumulating into a stack-local partial
        // --------------------------------------------------
        let frame_loop = self.frame_loop(driver);
        // --------------------------------------------------
        // the loop over the caller's cursor, or over a local copy written back after the block
        // every exit leaves
        // --------------------------------------------------
        let body = match self.cursor {
            CursorSite::Caller => quote! {
                let checkpoint = input.checkpoint();
                let mut __acc = <#partial_ty as ::core::default::Default>::default();
                #frame_loop
            },
            CursorSite::Local => quote! {
                let mut __cursor = ::core::clone::Clone::clone(&*input);
                let __result = '__tinyklv_decode: {
                    let input = &mut __cursor;
                    let checkpoint = input.checkpoint();
                    let mut __acc = <#partial_ty as ::core::default::Default>::default();
                    let mut __exact_reject: ::core::option::Option<&'static str> = ::core::option::Option::None;
                    #frame_loop
                };
                *input = __cursor;
                __result
            },
        };
        // --------------------------------------------------
        // emit the `DecodeValue` impl around the loop
        // --------------------------------------------------
        quote! {
            #[doc(hidden)]
            #[automatically_derived]
            #[doc = concat!(" [`", stringify!(#name), "`] implementation of [`tinyklv::prelude::DecodeValue`] for [`", stringify!(#stream), "`].")]
            impl #impl_generics ::tinyklv::traits::DecodeValue<#stream> for #name #ty_generics #where_clause {
                #pre_check_clippy_allow
                #[inline]
                fn decode_value(input: &mut #stream) -> ::tinyklv::__export::winnow::Result<Self> {
                    #body
                }
            }
        }
    }

    /// Generates the `DecodePartial` trait implementation for a container
    ///
    /// The emitted impl delegates entirely to `ResumePartial::resume_partial`,
    /// constructing a default partial struct and handing control over. This keeps
    /// the `DecodePartial` impl thin and ensures fresh-start and mid-stream
    /// resumption share identical logic
    ///
    /// # Returns
    ///
    /// A [`proc_macro2::TokenStream`] containing the complete `DecodePartial` impl block
    pub(super) fn decode_partial_impl(&self) -> TokenStream {
        let Self {
            input,
            ref stream,
            ref partial_ty,
            ..
        } = *self;
        let name = &input.ident;
        // --------------------------------------------------
        // split generics
        // --------------------------------------------------
        let (impl_generics, ty_generics, where_clause) = input.generics.split_for_impl();
        // --------------------------------------------------
        // fresh-start: build default partial and hand off to resume
        // --------------------------------------------------
        quote! {
            #[doc(hidden)]
            #[automatically_derived]
            #[doc = concat!(" [`", stringify!(#name), "`] implementation of [`tinyklv::prelude::DecodePartial`] for [`", stringify!(#stream), "`]")]
            impl #impl_generics ::tinyklv::traits::DecodePartial<#stream> for #name #ty_generics #where_clause {
                type Partial = #partial_ty;

                #[inline(always)]
                fn decode_partial(
                    input: &mut #stream,
                ) -> ::core::result::Result<
                    ::tinyklv::decoder::Packet<Self, Self::Partial>,
                    &'static str,
                > {
                    <Self as ::tinyklv::traits::ResumePartial<#stream>>::resume_partial(
                        input,
                        <#partial_ty as ::core::default::Default>::default(),
                    )
                }
            }
        }
    }
}

